// REQ-SILK-002: writes contracts/silks-code.vectors.json — the shared test vectors of the silks code (TS silksEditor.ts and
// C# Muchi.Client SilksCode both check against it). Re-run after adding parts: existing vectors must not change.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadMaster } from '../src/domain/master.js';
import { checkDesign, decodeSilksCode, designToCode, encodeSilksCode, legacyToDesign, type SilksDesign } from '../src/domain/silksEditor.js';

const m = loadMaster();
const designs: SilksDesign[] = [
  { pattern: 'plain', colors: ['white', 'navy'], sleeve: 'match', cap: 'plain', capColors: ['white', 'navy'] },
  { pattern: 'hoops', colors: ['navy', 'white'], sleeve: 'plain', cap: 'quartered', capColors: ['red', 'white'] },
  { pattern: 'stars', colors: ['crimson', 'gold', 'white'], sleeve: 'stars', cap: 'spots', capColors: ['crimson', 'gold'] },
  { pattern: 'quartered', colors: ['teal', 'black'], sleeve: 'armlets', cap: 'diamond', capColors: ['black', 'teal'] },
  { pattern: 'promo_s', colors: ['platinum', 'royal', 'sakura'], sleeve: 'diamonds', cap: 'checks', capColors: ['royal', 'platinum'] },
  { pattern: 'sash', colors: ['lime', 'purple'], sleeve: 'chevrons', cap: 'peak', capColors: ['emerald', 'yellow'] },
];
const legacy = [
  { pattern: 'stripes', colors: ['blue', 'yellow'], cap: 'star' },
  { pattern: 'braces', colors: ['brown', 'sky', 'orange'], cap: 'hooped' },
];
const numeric: (number | null)[][] = [
  [0, 0, 0, null, 0, 0, 0, 0],
  [1294, 1294, 1294, 1294, 1294, 1294, 1294, 1294],
  [35, 36, 71, null, 1, 10, 100, 1000],
];
export const INVALID_CODES = ['', '1', '2000000000000000z', '1000000000000000', '10000000000000000z', '1ZZ00000000000000', '1zz00000000000000', '100000000zz000000', '1-000000000000000', ' 0000000000000000'];
const out = {
  _note: 'REQ-SILK-002 (contracts/protocol.md §35.2): shared vectors for the silks code. Generated by server/scripts/gen-silks-vectors.ts from server/master/silks-editor.json; checked by server/test/silks-editor.test.ts and engine/Muchi.Engine.Tests/SilksCodeTests.cs.',
  numeric: numeric.map((n) => ({ numbers: n, code: encodeSilksCode(n) })),
  designs: designs.map((d) => ({ design: checkDesign(m, d), code: designToCode(m, d) })),
  legacy: legacy.map((s) => ({ silks: s, design: legacyToDesign(s), code: designToCode(m, checkDesign(m, legacyToDesign(s))) })),
  invalid: INVALID_CODES,
};
for (const c of out.invalid) if (decodeSilksCode(c) !== null) throw new Error(`vector ${JSON.stringify(c)} should be invalid`);
writeFileSync(resolve(dirname(fileURLToPath(import.meta.url)), '../../contracts/silks-code.vectors.json'), JSON.stringify(out, null, 2) + '\n');
console.log('wrote contracts/silks-code.vectors.json');
