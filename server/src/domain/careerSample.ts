// REQ-CAREER-019: every 騎手の道 race exactly as startCareerRace issues it to a player riding the partner horse, for the C#
// tests (contracts/career-configs.sample.json, written by scripts/gen-career-sample.ts; test/career.test.ts fails while the
// committed copy differs). A fixed player at a fixed time over the default ruleset, one seed per race.
import defaultRuleset from '../../../contracts/ruleset-params.default.json';
import type { Master } from './master.js';
import { newPlayer } from './player.js';
import { createHorseFromTemplate } from './horses.js';
import { careerOf, careerState, startCareerRace } from './career.js';
import type { Ruleset } from './ruleset.js';
import { seededRng } from './rng.js';

export const CAREER_SAMPLE_NOW = Date.UTC(2026, 10, 10, 3);

export function careerSampleJson(m: Master): string {
  const s = newPlayer('sample', CAREER_SAMPLE_NOW, 'S2026-11');
  const partner = createHorseFromTemplate(s, m.templateById.get('t_partner')!, CAREER_SAMPLE_NOW);
  const cm = careerOf(m);
  const st = careerState(s);
  const races: unknown[] = [];
  let i = 0;
  for (const ch of cm.chapters) {
    for (const race of ch.races) {
      const r = startCareerRace(m, s, race.id, partner.id, `sample${i}`, seededRng(4200 + i), CAREER_SAMPLE_NOW, () => undefined, defaultRuleset as unknown as Ruleset);
      races.push({ raceId: race.id, chapterId: ch.id, playerSlot: r.playerSlot, objectives: [race.clear, ...race.stars.map((x) => x.objective)], config: r.config });
      // open the next race as a clear would (the sample covers every race of the road)
      st.races[race.id]!.clearedAt = CAREER_SAMPLE_NOW;
      i++;
    }
  }
  st.sessions = [];
  return JSON.stringify({ _note: 'Generated by server/scripts/gen-career-sample.ts (npm run gen:career-sample). Do not edit.', races }, null, 1) + '\n';
}
