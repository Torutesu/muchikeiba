import localeEn from '../../master/locale-en.json';
import { CODE_EN } from './en.js';

/** master/locale-en.json + i18n/en.ts as one table (engine/Muchi.Client/Resources/Muchi/server-en.json). */
export function clientLocaleJson(): string {
  const strings: Record<string, string> = {};
  for (const [k, v] of Object.entries((localeEn as { strings: Record<string, string> }).strings)) if (!k.startsWith('_')) strings[k] = v;
  for (const [k, v] of Object.entries(CODE_EN)) strings[k] = v;
  return JSON.stringify({ _note: 'Generated by server/scripts/gen-client-locale.ts from server/master/locale-en.json and server/src/i18n/en.ts. Do not edit.', strings }, null, 1) + '\n';
}
