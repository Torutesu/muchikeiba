// Copies Codex's frontend stylesheets (frontend/src/style.css, details.css) into the club UI and generates
// site/club/codex/mobile.css: every rule inside Codex's narrow-screen media queries (max-width ≤ 1000px)
// repeated under `html.layout-mobile`, so the portrait/mobile layout can be forced from the toolbar (or picked
// automatically for portrait windows) at any window size. Codex's CSS stays the single source of truth.
// usage: node club-css.cjs <repo-root> <site>
const fs = require('fs');
const path = require('path');
const [root, site] = process.argv.slice(2);
const out = path.join(site, 'club', 'codex');
fs.mkdirSync(out, { recursive: true });

function blockEnd(css, open) { // index of the brace that closes the one at `open`
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) return i;
  }
  throw new Error('unbalanced braces');
}
const prefix = (selector) => selector.split(',').map((s) => {
  s = s.trim();
  if (s === ':root' || s === 'html') return 'html.layout-mobile';
  if (s.startsWith(':root') || s.startsWith('html')) return 'html.layout-mobile' + s.replace(/^(:root|html)/, '');
  return 'html.layout-mobile ' + s;
}).join(',');
function rules(inner) { // flat rule list "sel{decl}sel{decl}" → prefixed
  let res = '', i = 0;
  while (i < inner.length) {
    const open = inner.indexOf('{', i);
    if (open < 0) break;
    const close = blockEnd(inner, open);
    const sel = inner.slice(i, open).trim();
    const body = inner.slice(open, close + 1);
    if (sel.startsWith('@')) res += sel + '{' + rules(body.slice(1, -1)) + '}'; // nested at-rule (keyframes etc.)
    else if (sel) res += prefix(sel) + body;
    i = close + 1;
  }
  return res;
}

let mobile = '/* generated by tools/figma-prototype/club-css.cjs from Codex\'s frontend/src media queries */\n';
const widths = [];
for (const name of ['style.css', 'details.css']) {
  const css = fs.readFileSync(path.join(root, 'frontend', 'src', name), 'utf8');
  fs.writeFileSync(path.join(out, name), css);
  // keep source order: the 1000px block before the 650px block, style.css before details.css
  const re = /@media\s*\(max-width:\s*(\d+)px\)\s*\{/g;
  let m;
  while ((m = re.exec(css))) {
    const w = Number(m[1]);
    const open = m.index + m[0].length - 1;
    const close = blockEnd(css, open);
    if (w <= 1000) { mobile += rules(css.slice(open + 1, close)) + '\n'; widths.push(`${name}:${w}`); }
    re.lastIndex = close;
  }
}
fs.writeFileSync(path.join(out, 'mobile.css'), mobile);
console.log('club css', widths.join(' '), 'mobile.css', mobile.length, 'bytes');
